#!/usr/bin/env python3
"""
youtube_cookies_export.py

Convert an EditThisCookie JSON export of youtube.com into a Netscape
cookies.txt file that yt-dlp can consume for the Whisper audio fallback
(FIR-83 Run 4 follow-up).

Separate from the FIR-49 import_chrome_cookies.py path:
  - FIR-49: writes Playwright-format JSON to crawler_sessions DB (for FB/IG)
  - This:   writes Netscape cookies.txt file (yt-dlp --cookies flag format)

Steps:
  1. In Chrome, go to youtube.com → confirm logged in (avatar top-right)
  2. Click EditThisCookie extension icon → Export (clipboard icon)
  3. Save the JSON output to e.g. C:\\firstproject\\yt_cookies.json
  4. Run:
       python scripts/youtube_cookies_export.py \\
         --file yt_cookies.json \\
         --output yt_cookies.txt
  5. Add to .env:
       YOUTUBE_COOKIES_FILE=C:\\firstproject\\yt_cookies.txt
  6. Restart the API.

Auth-cookie sanity check warns if any of SID/HSID/SSID/LOGIN_INFO/SAPISID
is missing. YouTube sessions typically last ~6 months for LOGIN_INFO and
~6 weeks for the rotating SID family — re-export when audio download starts
returning "Sign in to confirm".

Requires: stdlib only.
"""

import argparse
import json
import sys
from pathlib import Path

_AUTH_COOKIES = {"SID", "HSID", "SSID", "LOGIN_INFO", "SAPISID", "APISID"}


def _to_netscape(raw: list[dict]) -> list[str]:
    """Convert EditThisCookie JSON entries to Netscape cookies.txt lines."""
    lines: list[str] = [
        "# Netscape HTTP Cookie File",
        "# Generated by youtube_cookies_export.py (FIR-83)",
    ]
    for c in raw:
        domain = str(c.get("domain") or "")
        if not domain:
            continue
        # Netscape "include subdomains" flag: TRUE when domain starts with '.'
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        path = c.get("path") or "/"
        secure = "TRUE" if c.get("secure") else "FALSE"
        # Session cookies have no expirationDate; encode as 0
        expiration = int(c.get("expirationDate") or 0)
        name = c.get("name") or ""
        value = c.get("value") or ""
        # Netscape format is tab-delimited, no quoting; drop tabs/newlines defensively
        for ch in ("\t", "\n", "\r"):
            value = value.replace(ch, "")
        lines.append(
            f"{domain}\t{include_sub}\t{path}\t{secure}\t{expiration}\t{name}\t{value}"
        )
    return lines


def main() -> None:
    parser = argparse.ArgumentParser(
        description="EditThisCookie JSON -> yt-dlp Netscape cookies.txt"
    )
    parser.add_argument(
        "--file", "-f", required=True,
        help="Path to the EditThisCookie JSON export (youtube.com cookies)"
    )
    parser.add_argument(
        "--output", "-o", default="yt_cookies.txt",
        help="Output cookies.txt path (default: yt_cookies.txt)"
    )
    args = parser.parse_args()

    project_root = Path(__file__).resolve().parent.parent
    cookie_file = Path(args.file)
    if not cookie_file.is_absolute():
        cookie_file = project_root / cookie_file
    if not cookie_file.exists():
        print(f"[ERROR] File not found: {cookie_file}")
        sys.exit(1)

    out_file = Path(args.output)
    if not out_file.is_absolute():
        out_file = project_root / out_file

    raw = json.loads(cookie_file.read_text(encoding="utf-8"))
    if not isinstance(raw, list):
        print("[ERROR] Expected a JSON array of cookies.")
        sys.exit(1)

    youtube_cookies = [
        c for c in raw
        if isinstance(c, dict) and "youtube" in str(c.get("domain", "")).lower()
    ]
    if not youtube_cookies:
        print("[ERROR] No youtube.com cookies in this file.")
        sys.exit(1)

    print(f"[*] Loaded {len(raw)} cookies; {len(youtube_cookies)} from youtube.com domains")

    found_auth = {c["name"] for c in youtube_cookies} & _AUTH_COOKIES
    missing_auth = _AUTH_COOKIES - found_auth
    if not found_auth:
        print("[ERROR] No auth cookies (SID/HSID/SSID/LOGIN_INFO/SAPISID) — are you logged into youtube.com?")
        sys.exit(1)
    print(f"[OK]  Auth cookies present: {', '.join(sorted(found_auth))}")
    if missing_auth:
        print(f"[INFO] Auth cookies missing (may be OK): {', '.join(sorted(missing_auth))}")

    lines = _to_netscape(youtube_cookies)
    out_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[OK]  Wrote {len(lines) - 2} cookie lines → {out_file}")
    print("[DONE] Add to .env:")
    print(f"       YOUTUBE_COOKIES_FILE={out_file}")
    print("       Then restart API.")


if __name__ == "__main__":
    main()
